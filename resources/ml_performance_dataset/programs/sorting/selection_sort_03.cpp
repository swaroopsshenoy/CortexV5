void selectionSort(vector<int>& arr) {
    int n = arr.size();
    for (int i = 0; i < n - 1; i++) {
        int minIdx = i;
        for (int j = i + 1; j < n; j++) {
            if (arr[j] < arr[minIdx]) minIdx = j;
        }
        swap(arr[i], arr[minIdx]);
    }
}
int main() {
    vector<int> arr = {9, 5, 2, 7, 1, 8, 3, 6, 4, 30};
    selectionSort(arr);
    for (int x : arr) cout << x << " ";
    return 0;
}
